"""Render the Birge brand assets from branding/brand.json.

The mark ("Shenber", a circle of six dots) is geometry, not artwork: this
script writes every SVG in branding/svg/ from the colours in brand.json and,
with --png, renders the PNG sizes the apps need into
apps/<app>/assets/brand/. To recolour the brand, edit brand.json and run it
again; never edit the generated files by hand.

    python3 branding/render.py          # SVGs only (standard library)
    python3 branding/render.py --png    # SVGs and PNGs (needs Playwright)

PNGs are rendered with headless Chromium through Playwright, for example in
the official image: docker run --rm -v "$PWD":/w -w /w
mcr.microsoft.com/playwright/python:v1.52.0-noble sh -c
"pip install playwright==1.52.0 && python3 branding/render.py --png".
"""

import json
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BRAND = ROOT / "branding"
SVG = BRAND / "svg"

# Geometry on a 512 grid: six dots on a connecting ring, the same at every
# size (owner, 2026-10-28: small sizes used to drop the ring and dots).
RING, DOT, RING_STROKE, CORNER = 124, 40, 16, 112
# Android adaptive icons crop to a 66/108 safe zone; the mark is scaled into it.
ADAPTIVE_SCALE = 0.72


def ring_el(colour: str, scale: float = 1.0, opacity: float = 1.0) -> str:
    alpha = f' stroke-opacity="{opacity}"' if opacity < 1 else ""
    return (
        f'<circle cx="256" cy="256" r="{RING * scale:.1f}" fill="none" stroke="{colour}"'
        f' stroke-width="{RING_STROKE * scale:.1f}"{alpha}/>'
    )


def dots(fill: str, scale: float = 1.0, ring: str | None = None) -> str:
    out = [ring_el(ring, scale)] if ring else []
    for k in range(6):
        a = math.radians(-90 + 60 * k)
        x, y = 256 + RING * scale * math.cos(a), 256 + RING * scale * math.sin(a)
        out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{DOT * scale:.1f}" fill="{fill}"/>')
    return "".join(out)


def svg(body: str, note: str = "") -> str:
    comment = f"<!-- {note} Generated by branding/render.py from brand.json. -->" if note else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">{comment}{body}</svg>\n'


def write_svgs(c: dict) -> dict:
    files = {
        "mark.svg": svg(
            ring_el("currentColor", opacity=0.45) + dots("currentColor"),
            "Mark only; currentColor takes the colour of its context (ring at 45%).",
        ),
        "icon.svg": svg(
            f'<rect width="512" height="512" rx="{CORNER}" fill="{c["background"]}"/>' + dots(c["mark"], ring=c["ring"]),
            "App icon.",
        ),
        "icon-dark.svg": svg(
            f'<rect width="512" height="512" rx="{CORNER}" fill="{c["backgroundDark"]}"/>'
            + dots(c["markDark"], ring=c["ringDark"]),
            "App icon for dark surfaces.",
        ),
        "icon-square.svg": svg(
            f'<rect width="512" height="512" fill="{c["background"]}"/>' + dots(c["mark"], ring=c["ring"]),
            "Full-bleed square: iOS rounds the corners itself.",
        ),
        "icon-adaptive-foreground.svg": svg(
            dots(c["mark"], ADAPTIVE_SCALE, ring=c["ring"]), "Android adaptive foreground (background: brand.json background)."
        ),
        "icon-monochrome.svg": svg(
            dots("#000000", ADAPTIVE_SCALE, ring="#000000"), "Android 13+ themed icon; the system tints it."
        ),
    }
    SVG.mkdir(exist_ok=True)
    for name, text in files.items():
        (SVG / name).write_text(text)
    return files


# PNG targets: (source svg, size, output path under ROOT, transparent).
PNGS = [
    ("icon-square.svg", 1024, "apps/mobile/assets/brand/icon.png", False),
    ("icon-adaptive-foreground.svg", 1024, "apps/mobile/assets/brand/adaptive-foreground.png", True),
    ("icon-monochrome.svg", 1024, "apps/mobile/assets/brand/adaptive-monochrome.png", True),
    ("icon.svg", 48, "apps/mobile/assets/brand/favicon.png", True),
    ("icon.svg", 192, "apps/mobile/public/icon-192.png", True),
    ("icon.svg", 512, "apps/mobile/public/icon-512.png", True),
    ("icon-square.svg", 512, "apps/mobile/public/icon-maskable-512.png", False),
    ("icon.svg", 48, "apps/admin/assets/brand/favicon.png", True),
]


def write_pngs(files: dict) -> None:
    from playwright.sync_api import sync_playwright  # only needed for --png

    with sync_playwright() as p:
        browser = p.chromium.launch()
        for src, size, out, transparent in PNGS:
            page = browser.new_page(viewport={"width": size, "height": size})
            page.set_content(
                "<html><body style='margin:0;background:transparent'>"
                f"<div style='width:{size}px;height:{size}px'>{files[src].replace('<svg ', f'<svg width=\"{size}\" height=\"{size}\" ', 1)}</div>"
                "</body></html>"
            )
            target = ROOT / out
            target.parent.mkdir(parents=True, exist_ok=True)
            page.screenshot(path=str(target), omit_background=transparent, clip={"x": 0, "y": 0, "width": size, "height": size})
            page.close()
        browser.close()


def main() -> None:
    colours = json.loads((BRAND / "brand.json").read_text())
    files = write_svgs(colours)
    # The web apps link the icon straight from public/.
    for app in ("mobile", "admin"):
        (ROOT / "apps" / app / "public" / "icon.svg").write_text(files["icon.svg"])
    if "--png" in sys.argv:
        write_pngs(files)
    print("rendered", len(files), "svgs", "and pngs" if "--png" in sys.argv else "")


if __name__ == "__main__":
    main()
